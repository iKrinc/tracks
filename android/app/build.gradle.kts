    }

    buildTypes {
        release {
            // The release key when key.properties exists (this PC); debug
            // keys elsewhere, so `flutter run --release` still works.
            signingConfig = signingConfigs.findByName("release")
                ?: signingConfigs.getByName("debug")
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }
}

